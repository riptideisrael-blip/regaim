    private val WORD = Regex("[א-ת֑-ׇ]+")

    /** [text] with niqqud on the words that have it here; [girl]: "אותך" said to a girl. */
    fun show(text: String, girl: Boolean = false): String {
        val words = WORD.findAll(text).toList()
        val sb = StringBuilder()
        var last = 0
        for ((i, m) in words.withIndex()) {
            sb.append(text, last, m.range.first)
            val w = m.value
            val next = words.getOrNull(i + 1)?.value.orEmpty()
            sb.append(when {
                w.any { it in '֑'..'ׇ' } -> w // already has niqqud
                // "you" (a girl: before "אלופה", or "עכשיו את!") or the object word
                w == "את" -> if (next.startsWith("אלופ") || text.getOrNull(m.range.last + 1) == '!') "אַתְּ" else "אֶת"
                w == "אותך" -> if (girl) "אוֹתָךְ" else "אוֹתְךָ"
                else -> WORDS[w] ?: w
            })
            last = m.range.last + 1
        }
        sb.append(text, last, text.length)
        return sb.toString()
    }
